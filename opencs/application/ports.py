"""Small structural contracts: domain/application never import adapter implementations."""

from contextlib import AbstractContextManager
from typing import Any, Protocol

from opencs.domain import Conversation, Customer, Interaction


class EntityRepository(Protocol):
    def get_customer(self, tenant_id: str, customer_id: str, /) -> Customer: ...
    def get_conversation(self, tenant_id: str, conversation_id: str, /) -> Conversation: ...
    def update_conversation(self, conversation: Conversation) -> None: ...
    def add_interaction(self, interaction: Interaction) -> None: ...
    def list_interactions(self, tenant_id: str, conversation_id: str, /) -> list[Interaction]: ...


class AgentPort(Protocol):
    def decide(self, context: dict[str, Any]) -> dict[str, Any]: ...


class ToolPort(Protocol):
    def execute(
        self, name: str, arguments: dict[str, Any], *, tenant_id: str, action_id: str
    ) -> dict[str, Any]: ...


class ChannelPort(Protocol):
    def send(
        self, *, tenant_id: str, conversation_id: str, text: str, action_id: str
    ) -> dict[str, Any]: ...

    def handoff(
        self, *, tenant_id: str, conversation_id: str, snapshot: dict[str, Any], action_id: str
    ) -> dict[str, Any]: ...


class RuntimeStore(Protocol):
    """Atomic claims/checkpoints. Durability is a concrete store responsibility.

    Current MemoryRuntimeStore is a process-local test implementation, not a
    PostgreSQL transaction substitute. Returned objects must be isolated copies.
    """

    def locked(self) -> AbstractContextManager[None]: ...
    def processing(self, tenant_id: str, conversation_id: str) -> AbstractContextManager[None]: ...
    def claim(self, event: dict[str, Any]) -> tuple[bool, dict[str, Any]]: ...
    def finish(self, tenant_id: str, event_id: str, result: dict[str, Any]) -> None: ...
    def append_audit(
        self, tenant_id: str, conversation_id: str, kind: str, data: dict[str, Any]
    ) -> str: ...
    def list_audit(self, tenant_id: str, conversation_id: str) -> list[dict[str, Any]]: ...
    def get_handoff(self, tenant_id: str, conversation_id: str) -> dict[str, Any] | None: ...
    def save_handoff(self, snapshot: dict[str, Any]) -> None: ...
